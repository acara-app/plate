</p>

<h2>7. Төлбөртэй багц, багцаа цуцлах</h2>
<p>
    <strong>а. Төлбөр:</strong>
    Төлбөртэй багцыг зөвхөн Acara Plate-ийн вэбсайтаас худалдан авч, удирдана. Төлбөрийг Stripe боловсруулна.
    Багцыг цуцлах хүртэл худалдан авах үед заасан үнээр сар бүр эсвэл жил бүр автоматаар сунгана. Апп дэлгүүрээс
    худалдан авсан захиалгад Acara Plate-ийн багц хэзээ ч багтдаггүй бөгөөд аппыг устгаснаар багц цуцлагдахгүй.
</p>
<p>
    <strong>б. Багцаа цуцлах:</strong>
    Та Төлбөрийн тохиргооны “Багцаа удирдах” хэсгээс хүссэн үедээ багцаа цуцлах боломжтой. Мөн
    <a href="mailto:support@acara.app">support@acara.app</a> хаягаар хүсэлт илгээж багцаа цуцлуулж болно.
</p>
<p>
    <strong>в. Цуцлалт хүчин төгөлдөр болох:</strong>
    Багцыг цуцалснаар дараагийн сунгалт хийгдэхгүй. Өөрөөр тохиролцоогүй бол та төлбөрөө төлсөн хугацаа дуусах
    хүртэл багцын бүх боломжийг ашиглана. Үүний дараа таны бүртгэл үнэгүй багц руу шилжих бөгөөд та бүртгэлээ
    устгах хүртэл таны мэдээлэл хадгалагдана.
</p>
<p>
    <strong>г. Баталгаажуулах цахим шуудан:</strong>
    Багцыг та өөрөө цуцалсан эсвэл таны хүсэлтээр цуцалсан эсэхээс үл хамааран багц цуцлагдах бүрд таны цахим
    шууданд мэдэгдэл илгээнэ. Хэрэв та цуцлах хүсэлт гаргаагүй атлаа ийм мэдэгдэл хүлээн авсан бол бидэнтэй
    яаралтай холбогдоно уу.
</p>
<p>
    <strong>д. Бүртгэлээ устгах:</strong>
    Бүртгэлээ устгахаас өмнө багцаа цуцална уу.
</p>

