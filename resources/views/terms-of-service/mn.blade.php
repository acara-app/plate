<h2>9. Баталгаа болон хариуцлагын хязгаарлалт</h2>
<p>
    Үйлчилгээг “байгаа байдлаар нь” үзүүлэх бөгөөд биет байдлын доголдолгүй байх, тодорхой зориулалтаар ашиглах боломжтой байх, эрхийн доголдолгүй байх зэрэг илэрхий болон далд аливаа баталгаа гаргахгүй.
</p>
<p>
    <strong>Хариуцлага хүлээхгүй:</strong> Хуулиар зөвшөөрөгдөх дээд хэмжээнд Acara Plate, түүний зохиогч, хувь нэмэр оруулагч, лиценз олгогч нь шууд, шууд бус, дагалдах, тусгай, үр дагаврын хохирол, шийтгэлийн шинжтэй нөхөн төлбөр, шууд болон шууд бусаар учирсан ашиг, орлогын алдагдал, эсвэл мэдээлэл, ашиглалт, ажил хэргийн нэр хүндийн алдагдал болон бусад эдийн бус хохирлыг хариуцахгүй. Энэ нь дараах үйл явдлаас үүдэлтэй хохиролд хамаарна: а) таны Үйлчилгээнд хандах, түүнийг ашиглах, эсвэл хандаж, ашиглаж чадаагүй байдал; б) Үйлчилгээн дэх гуравдагч этгээдийн аливаа үйлдэл, агуулга; в) таны дамжуулсан мэдээлэл, агуулгад зөвшөөрөлгүй хандах, ашиглах, өөрчлөх.
</p>

