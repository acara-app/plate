<h1>Үйлчилгээний нөхцөл</h1>
<p><strong>Сүүлд шинэчилсэн огноо: {{ $effectiveDate }}</strong></p>
<p>
    Acara Plate-д тавтай морил. Acara Plate нь хиймэл оюун ухаанд суурилсан хоолны төлөвлөгөө, хооллолтын
    хэрэгслээр дамжуулан хувьд тохирсон хооллолтын зөвлөгөө өгөх зорилготой нээлттэй эхийн платформ бөгөөд iOS-д
    зориулсан Acara Health Sync дагалдах аппыг багтаадаг. Манай вэбсайт, апп, үйлчилгээнд (цаашид хамтад нь
    “Үйлчилгээ” гэх) хандах эсвэл тэдгээрийг ашигласнаар та энэхүү Үйлчилгээний нөхцөлийг (цаашид “Нөхцөл” гэх)
    дагаж мөрдөхийг зөвшөөрч байна.
</p>

<h2>1. Нөхцөлийг хүлээн зөвшөөрөх</h2>
<p>
    Бүртгэл үүсгэх эсвэл Үйлчилгээг ашигласнаар та энэхүү Нөхцөлийг зөвшөөрч байна. Хэрэв та зөвшөөрөхгүй бол
    Үйлчилгээг ашиглах эрхгүй. Acara Plate энэхүү Нөхцөлд өөрийн үзэмжээр нэмэлт, өөрчлөлт оруулж болно. Өөрчлөлт
    орсны дараа та Үйлчилгээг үргэлжлүүлэн ашиглавал шинэчилсэн Нөхцөлийг хүлээн зөвшөөрсөнд тооцно.
</p>

<h2>2. Үйлчилгээ ашиглах</h2>
<p>
    <strong>а. Ашиглах эрх:</strong>
    Үйлчилгээ эрүүл мэндийн эмзэг мэдээлэл цуглуулдаг тул та Үйлчилгээг ашиглахын тулд 18 нас хүрсэн байх ёстой.
    Энэ шаардлага нь холбогдох хууль тогтоомж, түүний дотор Европын холбооны хэрэглэгчдийн хувьд Хувийн мэдээлэл
    хамгаалах ерөнхий журамд (GDPR) нийцнэ. Та хүчин төгөлдөр гэрээ байгуулах насанд хүрсэн гэдгээ баталж байна.
</p>
<p>
    <strong>б. Бүртгэл:</strong>
    Хувийн хооллолтын асуулга зэрэг боломжийг ашиглахад бүртгэл шаардлагатай байж болно. Та бүртгэл, нууц
    үгийнхээ нууцлалыг хадгалах, мөн бүртгэлээрээ хийгдсэн бүх үйлдлийг хариуцна.
</p>
<p>
    <strong>в. Зөвшөөрөгдөх хэрэглээ:</strong>
    Та Үйлчилгээг хууль бус зорилгоор ашиглахгүй, Үйлчилгээнд хор хохирол учруулж, хэвийн ажиллагааг нь
    алдагдуулахгүй, бусдын ашиглалтад саад учруулахгүй байхыг зөвшөөрч байна. Хооллолтын зөвлөмжийн нарийвчлалд
    нөлөөлж болзошгүй тул асуулгад худал эсвэл төөрөгдүүлэх мэдээлэл оруулахыг хориглоно.
</p>

<h2>3. Хэрэглэгчийн мэдээлэл</h2>
<p>
    <strong>а. Таны мэдээлэл:</strong>
    Та асуулгаар дамжуулан өгсөн биеийн үзүүлэлт, хооллолтын сонголт, эрүүл мэндийн байдал зэрэг мэдээллээ
    хариуцна. Та холбогдох хууль тогтоомж, түүний дотор Европын холбоонд оршин суугчдын хувьд GDPR-ыг дагаж мөрдөх
    ёстой. Acara Plate таны мэдээллийн үнэн зөвийг шалгахгүй.
</p>
<p>
    <strong>б. Мэдээллийг ашиглах:</strong>
    Мэдээлэл оруулснаар та Нууцлалын бодлогод заасны дагуу хоолны төлөвлөгөө, хооллолтын зөвлөмж зэрэг Үйлчилгээг
    үзүүлэх зорилгоор таны мэдээллийг ашиглах, хадгалах, боловсруулах дэлхий даяар хүчинтэй, ашигласны төлбөргүй
    энгийн лицензийг Acara Plate-д олгож байна. Та мэдээлэл эсвэл бүртгэлээ устгах үед энэ лиценз дуусгавар болно.
    Харин хүнийг тодорхойлох боломжгүй болгосон эсвэл нэгтгэсэн хэлбэрээр хуваалцсан мэдээлэлд энэ нь хамаарахгүй.
</p>
<p>
    <strong>в. Мэдээллийн нууцлал:</strong>
    Acara Plate таны мэдээллийг GDPR болон холбогдох бусад хууль тогтоомжийн дагуу хамгаална. Таны мэдээллийг
    (жишээ нь, эрүүл мэндийн байдал, хооллолтын сонголт) аюулгүй хадгалж, зөвхөн Нууцлалын бодлогод заасны дагуу
    ашиглана. Нууцлалын бодлогод таны эрх болон бид мэдээллийг тань хэрхэн боловсруулдгийг мөн тайлбарласан.
</p>
<p>
    <strong>г. Хориотой мэдээлэл:</strong>
    Хууль бус, төөрөгдүүлэх, хор хөнөөлтэй, эсвэл гуравдагч этгээдийн эрхийг зөрчсөн мэдээлэл, түүний дотор эрүүл
    мэндийн худал мэдээлэл оруулахыг хориглоно. Acara Plate энэхүү Нөхцөлийг зөрчсөн аливаа мэдээллийг устгаж
    болно.
</p>
<p>
    <strong>д. Зөрчлийн талаар мэдэгдэх:</strong>
    Хэрэв Acara Plate дээрх аливаа мэдээлэл таны эрхийг зөрчиж байна гэж үзвэл дэлгэрэнгүй мэдэгдлийн хамт
    бидэнтэй холбогдоно уу. Бид зохих арга хэмжээ авна.
</p>

<h2>4. Оюуны өмч</h2>
<p>
    Үйлчилгээ, түүний боломж, агуулга (таны мэдээллээс бусад) нь Acara Plate болон түүнд лиценз олгогчийн өмч юм.
    Та зөвшөөрөлгүйгээр Үйлчилгээг хуулбарлах, өөрчлөх, түгээхийг хориглоно.
</p>

<h2>5. Эрүүл мэнд, хоол тэжээлийн талаарх анхааруулга</h2>
<p>
    <strong>Эмнэлгийн зөвлөгөө биш:</strong> Acara Plate нь эмнэлгийн тусламж, үйлчилгээ биш бөгөөд мэргэжлийн эмнэлгийн зөвлөгөө, оношилгоо, эмчилгээний зөвлөмж өгөхгүй. Хиймэл оюун ухаанаар үүсгэсэн хоолны төлөвлөгөө, хоол тэжээлийн дүгнэлт, цусны сахар хянах боломж зэрэг Үйлчилгээ нь зөвхөн мэдээлэл, танин мэдэхүйн зорилготой.
</p>
<p>
    <strong>Мэргэжилтэнтэй зөвлөлдөх:</strong> Эрүүл мэндийн байдал, хооллолтын өөрчлөлт эсвэл цусны сахараа хянах талаар асуух зүйл гарвал эмч, мэргэжлийн хоол зүйч эсвэл бусад эмнэлгийн мэргэжилтэнтэй заавал зөвлөлдөнө үү. Үйлчилгээнээс уншсан зүйлдээ үндэслэн мэргэжлийн эмнэлгийн зөвлөгөөг хэзээ ч үл тоомсорлож, эсвэл зөвлөгөө авахаа хойшлуулж болохгүй.
</p>
<p>
    <strong>Хиймэл оюун ухааны хязгаарлалт:</strong> Хоолны төлөвлөгөө болон хоол тэжээлийн мэдээллийг хиймэл оюун ухаан үүсгэдэг. Бид үнэн зөв байлгахыг хичээдэг ч хиймэл оюун ухааны загвар харшил үүсгэгч, орц эсвэл макро тэжээлийн хэмжээний талаар заримдаа буруу мэдээлэл гаргаж болно. Хэрэглэхээсээ өмнө бүх орц, хоол тэжээлийн агуулгыг бие даан шалгах үүргийг та хариуцна.
</p>
<p>
    <strong>Apple Health-ийн мэдээлэл:</strong> Хэрэв та Acara Health Sync дагалдах аппыг ашигладаг бол Apple Health-ийн эрүүл мэндийн мэдээллийг зөвхөн уншиж авах бөгөөд таны төхөөрөмж дээр шифрлээд таны ашиглаж буй Acara Plate системд шууд дамжуулна. Энэ мэдээллийг зөвхөн таны хувийн хооллолтын зөвлөгөөг сайжруулахад ашиглах бөгөөд гуравдагч этгээдэд хэзээ ч дамжуулахгүй, зар сурталчилгаанд ашиглахгүй, худалдахгүй. Та Apple Health-д хандах зөвшөөрлийг iPhone-ийн Settings (Тохиргоо) хэсгээс хүссэн үедээ цуцалж болно.
</p>

<h2>6. Нээлттэй эх</h2>
