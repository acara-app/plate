<h2>1. Бидний цуглуулдаг мэдээлэл</h2>
<p>Бид хувьд тань тохирсон хооллолтын зөвлөгөө өгөхийн тулд дараах төрлийн мэдээллийг цуглуулдаг:</p>
<p>
    <strong>а. Хувийн мэдээлэл:</strong>
    Таныг хооллолтын асуулга бөглөх эсвэл бүртгэл үүсгэх үед бид дараах мэдээллийг цуглуулж болно:
<ul>
    <li><strong>Биеийн үзүүлэлт:</strong> нас, өндөр, жин, хүйс.</li>
    <li><strong>Зорилго:</strong> хооллолтын зорилго (жишээ нь, жин хасах, булчингийн жин нэмэх, эрүүл мэндийн
        асуудлаа хянах).</li>
    <li><strong>Нэмэлт зорилго (чөлөөт бичвэр):</strong> зорилгоо өөрийн үгээр бичих сонголттой талбар. Энэ талбарт ямар ч бичвэр оруулж болох тул хиймэл оюун ухааны үйлчилгээ үзүүлэгчээр боловсруулуулахыг хүсэхгүй байгаа эрүүл мэндийн эмзэг мэдээллээ бүү бичээрэй (5 дугаар хэсгийг үзнэ үү).</li>
    <li><strong>Амьдралын хэв маяг:</strong> хөдөлгөөний идэвх, нойрны хэв маяг, ажил мэргэжил.</li>
    <li><strong>Хооллолтын сонголт:</strong> харшил, үл тэсвэрлэлт (жишээ нь, глютен, лактоз), хооллолтын хэв
        маяг (жишээ нь, веган, кето), дургүй хоол хүнс.</li>
    <li><strong>Эрүүл мэндийн байдал:</strong> өвчин, эмгэг (жишээ нь, чихрийн шижин, цусны даралт ихсэх).
    </li>
    <li><strong>Холбоо барих мэдээлэл:</strong> цахим шуудангийн хаяг (бүртгэлээ удирдахад ашиглана).</li>
</ul>
</p>
<p>
    <strong>б. Apple Health-ийн мэдээлэл (Acara Health Sync-ээр дамжуулан):</strong>
