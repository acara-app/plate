<h2>3. Мэдээлэл боловсруулах эрх зүйн үндэслэл (GDPR)</h2>
<p>Европын холбоонд байгаа хэрэглэгчийн хувийн мэдээллийг бид дараах эрх зүйн үндэслэлээр боловсруулна:</p>
<ul>
    <li><strong>Зөвшөөрөл:</strong> та асуулга илгээх эсвэл бүртгэл үүсгэх замаар зөвшөөрлөө
        өгнө.</li>
    <li><strong>Тодорхой илэрхийлсэн зөвшөөрөл (GDPR-ын 9 дүгээр зүйл):</strong> эмзэг мэдээллийг (эрүүл мэндийн байдал, эм, биеийн үзүүлэлт, хоол, цусны сахарын хэмжилт болон эрүүл мэндтэй холбоотой бусад мэдээлэл) бид таны тодорхой илэрхийлсэн зөвшөөрлийн үндсэн дээр боловсруулна. Та энэ зөвшөөрлийг бүртгүүлэхдээ тусдаа нүдийг чагтлах замаар өгнө. Бид таныг хэзээ зөвшөөрөл өгснийг бүртгэж хадгална. Та энэ зөвшөөрлөө хүссэн үедээ цуцалж болно (8 дугаар хэсгийг үзнэ үү). Үйлчилгээ энэ мэдээлэлд тулгуурладаг тул зөвшөөрлөө цуцлах нь бүртгэлээ хаах гэсэн үг юм.</li>
    <li><strong>Гэрээний хэрэгжилт:</strong> Үйлчилгээг үзүүлэхийн тулд (жишээ нь, хоолны төлөвлөгөө гаргахад)
        мэдээлэл боловсруулах шаардлагатай.</li>
    <li><strong>Хууль ёсны ашиг сонирхол:</strong> бид Үйлчилгээг сайжруулахын тулд нэргүйжүүлсэн мэдээлэл болон
        хадгалсан хоолны тооцооллын нарийвчлалын нэгтгэсэн статистикийг (2 дугаар хэсгийг үзнэ үү) ашиглана.
        Ингэхдээ таны хувийн нууцад үзүүлэх нөлөөллийг хамгийн бага байлгана.</li>
</ul>

<h2>4. Мэдээллийг бусдад дамжуулах</h2>
<p>Бид таны хувийн мэдээллийг худалдахгүй. Бид мэдээллийг зөвхөн дараах этгээдэд, дараах тохиолдолд дамжуулна:</p>
<ul>
    <li>Үйлчилгээг ажиллуулахад бидний татан оролцуулдаг <strong>үйлчилгээ үзүүлэгчид</strong>. Үүнд сервер байршуулах (хостинг) үйлчилгээ үзүүлэгч, цахим шуудан хүргэх үйлчилгээ, мөн хариулт, хураангуй, вектор дүрслэл (embedding) гаргах, яриаг бичвэрт буулгах зорилгоор таны мэдээллийг боловсруулдаг <strong>хиймэл оюун ухааны үйлчилгээ үзүүлэгч</strong> багтана (одоогийн жагсаалт болон дамжуулж буй мэдээллийн төрлийг 5 дугаар хэсгээс үзнэ үү). Бүх үйлчилгээ үзүүлэгч мэдээлэл боловсруулах гэрээ, нууцлалын үүрэг хүлээсэн.</li>
    <li>Хуульд заасан тохиолдолд (жишээ нь, хуульд заасан үүргээ биелүүлэх эсвэл хэрэглэгчийн аюулгүй байдлыг хамгаалах).</li>
    <li>Үйлчилгээг сайжруулах дүн шинжилгээ, судалгааны зорилгоор нэргүйжүүлсэн эсвэл нэгтгэсэн хэлбэрээр.</li>
</ul>

<h2>5. Хиймэл оюун ухаанаар мэдээлэл боловсруулах, том хэлний загвар (LLM) нийлүүлэгч гуравдагч этгээд</h2>
<p>
    Acara Plate нь Altani (таны хиймэл оюун ухаант эрүүл мэндийн зөвлөх), хоолны төлөвлөгөө гаргах, цусны сахарын дүгнэлт, харилцан ярианы хураангуй болон хиймэл оюун ухаанд суурилсан бусад зөвлөгөөг ажиллуулахдаа гуравдагч этгээдийн хиймэл оюун ухааны (AI) үйлчилгээ үзүүлэгчийг ашигладаг. Та эдгээр боломжийг ашиглах үед таны хувийн мэдээллийн тодорхой зорилгод хамаарах хязгаарлагдмал хэсгийг хариулт гаргуулах (inference) зорилгоор эдгээр үйлчилгээ үзүүлэгчид дамжуулна.
</p>
<p>
    <strong>а. Одоогоор бидний ашиглаж буй үйлчилгээ үзүүлэгч:</strong>
<ul>
    <li><strong>OpenAI</strong> — харилцан ярианы чат (Altani чат туслах), хоолны төлөвлөгөө болон өдөр тутмын хоолны санал гаргах, цусны сахарын дүгнэлт, харилцан ярианы хураангуй, дуу хоолойг бичвэрт буулгах, бичвэрийн вектор дүрслэл (embedding).</li>
    <li><strong>Google</strong> — хоолны зургийн шинжилгээ болон Acara Cloud-ын урт хугацааны санах ойн боломж. Эдгээрийг Gemini болон Google-ийн ижил API холболтоор үйлчилдэг, Google-д байршдаг дараагийн үеийн эсвэл тусгайлсан загварууд гүйцэтгэнэ.</li>
</ul>
Бид тус тусын загварыг бус, <strong>мэдээлэл боловсруулагчийг</strong> нэрлэн мэдээлдэг. Нэг мэдээлэл боловсруулагчийн санал болгож буй өөр загварт шилжих нь (жишээ нь, Gemini-ийн шинэ хувилбар эсвэл Google-д байршдаг эмнэлгийн тусгай загвар) таны мэдээллийг хүлээн авах компанийг өөрчлөхгүй тул тусад нь мэдэгдэх шаардлагагүй. Таны мэдээлэлд шинэ <strong>мэдээлэл боловсруулагч</strong> (өөр компани эсвэл өөрсдийн серверт байршуулсан систем) нэмэгдэх тохиолдолд л бид энэ жагсаалтыг шинэчилнэ.
</p>
<p>
    <strong>б. Хиймэл оюун ухааны үйлчилгээ үзүүлэгчид дамжуулах мэдээлэл:</strong>
    Та хиймэл оюун ухаанд суурилсан боломжийг ашиглах үед бид дараах мэдээллийг дамжуулна:
<ul>
    <li>Таны чатад бичсэн зурвас.</li>
