    хадгална. Үүнд хиймэл оюун ухааны таньсан хоол хүнс, тэдгээрийн хэмжээ, илчлэг, макро тэжээл, хиймэл оюун
    ухаан хэр итгэлтэй байсан, мөн манай шинжилгээний аль хувилбараар тооцоолсон зэрэг орно. Хэрэв та дараа нь
    хоолны найрлага эсвэл хэмжээг өөрчилбөл бид таны юуг өөрчилснийг мөн тэмдэглэнэ. Эдгээр мэдээлэлд таны зураг,
    тэмдэглэл, хоолны нэр хэзээ ч орохгүй.
