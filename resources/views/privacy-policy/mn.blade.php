Бид энэ мэдээллийг зөвхөн уншиж авна. Acara Health Sync нь Apple Health-д ямар нэг мэдээлэл бичихгүй. Apple Health-ийн бүх мэдээллийг дамжуулахаас өмнө таны төхөөрөмж дээр шифрлэж, таны ашиглаж буй Acara Plate системд шууд илгээнэ. Apple Health-ийн мэдээллийг зөвхөн таны хиймэл оюун ухаант эрүүл мэндийн зөвлөх Altani-гийн өгөх хувийн хооллолтын зөвлөгөө, эрүүл мэндийн дүгнэлтэд ашиглана. Бид Apple Health-ийн мэдээллийг зар сурталчилгаа, маркетинг эсвэл өгөгдөл олборлох зорилгоор ашиглахгүй.
</p>
<p>
    <strong>в. Хувийн бус мэдээлэл:</strong>
