<h2>2. Мэдээллийг ашиглах зорилго</h2>
<p>Бид таны мэдээллийг Үйлчилгээг үзүүлэх, сайжруулах зорилгоор ашиглана. Үүнд:</p>
<ul>
    <li>Асуулгад өгсөн хариултад тань үндэслэн хувьд тохирсон хоолны төлөвлөгөө, хооллолтын зөвлөмж
        гаргах.</li>
    <li>Хооллолтын хязгаарлалтад (жишээ нь, харшил, веган хооллолт) нийцүүлэн хоолны төлөвлөгөөг шүүх.</li>
    <li>Таны бүртгэлийг удирдах, тантай харилцах (жишээ нь, үйлчилгээний шинэчлэлийн талаар мэдэгдэх).</li>
    <li>Үйлчилгээг сайжруулах, шинэ боломж хөгжүүлэхийн тулд нэргүйжүүлсэн мэдээлэлд дүн шинжилгээ хийх.</li>
    <li>Хоолны тооцооллынхоо нарийвчлалыг хэмжих, сайжруулах. Үүний тулд бид зөвхөн нэгтгэсэн статистик
        мэдээллийг, тухайлбал тухайн хоолны тооцоог хэр олон удаа зассаныг харна. Ингэхдээ зөвхөн 10-аас доошгүй
        хоол бүхий бүлгийг харна. Энэ зорилгоор хэн ч таны хоолыг нэг бүрчлэн хянахгүй.</li>
    <li>Хэрэв та “Хоол танилтыг сайжруулахад туслах” тохиргоог асаавал (та өөрөө сонгохгүй бол унтраалттай байна) манай баг
        хиймэл оюун ухаан хоолыг хэрхэн танихыг шалгах, сайжруулах зорилгоор таны хоол, засвар, хоолны зургийг нэг
        бүрчлэн харж болно. Эдгээр нь зөвхөн Acara дотор үлдэх бөгөөд бусад байгууллагад хэзээ ч дамжуулахгүй.
        Бид зургийг ашиглахаас өмнө хүний нүүр болон хувийн бусад мэдээлэл байгаа эсэхийг шалгана. Та энэ
        тохиргоог “Тохиргоо → Нууцлал” хэсгээс хүссэн үедээ унтрааж болох бөгөөд түүнээс хойш бид эдгээрийг энэ
        зорилгоор ашиглахаа зогсооно.</li>
</ul>
<p>Бид таны зөвшөөрөлгүйгээр мэдээллийг тань энэхүү Нууцлалын бодлогод заагаагүй зорилгоор ашиглахгүй.
