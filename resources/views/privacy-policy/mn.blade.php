<ul>
    <li><strong>Глюкоз:</strong> цусны сахарыг тасралтгүй хэмжигч төхөөрөмжийн болон гараар оруулсан цусны сахарын хэмжилт.</li>
    <li><strong>Амин үзүүлэлт:</strong> зүрхний цохилт, зүрхний цохилтын хэлбэлзэл, цусны даралт, цусны хүчилтөрөгчийн хангамж, амьсгалын тоо.</li>
    <li><strong>Биеийн хэмжээ:</strong> жин, биеийн жингийн индекс (БЖИ), өөхний эзлэх хувь, өндөр.</li>
    <li><strong>Хөдөлгөөн:</strong> алхамын тоо, идэвхтэй зарцуулсан илчлэг, дасгал, дугуй унах, усанд сэлэх.</li>
    <li><strong>Нойр:</strong> нойрны үе шат (REM, Core, Deep), орондоо байсан хугацаа.</li>
    <li><strong>Хоол тэжээл:</strong> илчлэгийн хэрэглээ, макро тэжээл, витамин, эрдэс бодис, усны хэрэглээ.</li>
