    serveurs sécurisés, pour protéger vos données. Cependant, aucun système n'est entièrement sûr, et nous ne pouvons pas
    garantir une sécurité absolue. Vous êtes responsable de la confidentialité de vos identifiants de compte.
</p>

<h2>7. Conservation des données</h2>
<p>
    Nous conservons vos renseignements personnels seulement le temps nécessaire pour fournir les Services ou respecter nos
    obligations légales. Vous pouvez demander la suppression de vos données à tout moment (voir la section 8). Les
    données anonymisées peuvent être conservées indéfiniment à des fins d'analyse.
</p>
<p>
    <strong>Récupération des numérisations :</strong>
    L'analyseur de photos public conserve temporairement une copie chiffrée de la photo téléversée afin que le traitement
    puisse reprendre après une interruption de connexion. Cette copie de récupération est supprimée après une numérisation
    réussie. Une numérisation qui échoue peut être relancée pendant une heure au plus; les enregistrements de récupération
    expirés sont supprimés par un nettoyage planifié. Ces copies de récupération temporaires sont distinctes des photos
    enregistrées avec un repas.
</p>
<p>
    <strong>Photos de repas :</strong>
    Les photos que vous numérisez avec Snap to Track lorsque vous avez ouvert une session sont conservées de façon privée
    avec votre journal alimentaire afin que vous puissiez les consulter plus tard. Avant de les conserver, nous
    redimensionnons chaque photo et en retirons la localisation et les autres métadonnées. Vous êtes la seule personne à
    pouvoir voir vos photos de repas, sauf si vous activez Aider à améliorer la reconnaissance des aliments (voir la
    section 2). Une photo est supprimée lorsque vous supprimez ce repas ou votre compte, ou après une journée si vous
    n'enregistrez pas le repas.
</p>
<p>
    <strong>Estimations de repas par l'IA :</strong>
    L'estimation initiale de l'IA et vos modifications sont conservées avec le repas auquel elles se rapportent. Elles
    sont supprimées lorsque vous supprimez ce repas ou votre compte, et automatiquement 12 mois après l'enregistrement du
    repas. Le repas lui-même reste dans votre journal alimentaire.
</p>
<p>
    <strong>Vos choix en matière de confidentialité :</strong>
    Nous conservons une trace de chaque choix que vous faites concernant Aider à améliorer la reconnaissance des aliments
    (ce que vous avez choisi et quand) tant que vous avez un compte, afin de pouvoir démontrer que nous l'avons respecté.
</p>

