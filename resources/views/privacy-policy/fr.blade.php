<h1>Politique de confidentialité</h1>
<p><strong>Date d'entrée en vigueur : {{ $effectiveDate }}</strong></p>
<p>
    Chez Acara Plate, nous accordons une grande importance à votre vie privée et nous nous engageons à protéger vos
    renseignements personnels. La présente politique de confidentialité explique comment nous recueillons, utilisons,
    conservons et protégeons les renseignements que vous nous fournissez au moyen de notre site Web, de nos applications
    et de nos services (collectivement, les « Services »), y compris notre questionnaire nutritionnel personnalisé et
    l'application compagnon Acara Health Sync pour iOS. En utilisant les Services, vous acceptez la présente politique
    de confidentialité.
</p>

<h2>1. Renseignements que nous recueillons</h2>
<p>Nous recueillons les types de renseignements suivants afin de vous offrir des conseils nutritionnels personnalisés :</p>
<p>
    <strong>a. Renseignements personnels :</strong>
    Lorsque vous remplissez notre questionnaire nutritionnel ou créez un compte, nous pouvons recueillir :
<ul>
    <li><strong>Données biométriques :</strong> âge, taille, poids, sexe.</li>
    <li><strong>Objectifs :</strong> objectifs nutritionnels (p. ex., perte de poids, prise de masse musculaire, gestion
        de problèmes de santé).</li>
    <li><strong>Objectifs supplémentaires (texte libre) :</strong> un champ facultatif en texte libre où vous décrivez vos objectifs dans vos propres mots. Comme ce champ accepte n'importe quel texte, évitez d'y inscrire des détails médicaux sensibles que vous ne souhaitez pas faire traiter par des fournisseurs d'IA (voir la section 5).</li>
    <li><strong>Mode de vie :</strong> niveau d'activité, habitudes de sommeil, profession.</li>
    <li><strong>Préférences alimentaires :</strong> allergies, intolérances (p. ex., gluten, lactose), habitudes
        alimentaires (p. ex., végétalienne, cétogène), aliments que vous n'aimez pas.</li>
    <li><strong>Problèmes de santé :</strong> affections médicales (p. ex., diabète, hypertension artérielle).
    </li>
    <li><strong>Coordonnées :</strong> adresse courriel (pour la gestion du compte).</li>
</ul>
</p>
<p>
    <strong>b. Données d'Apple Santé (au moyen d'Acara Health Sync) :</strong>
    Si vous utilisez l'application compagnon Acara Health Sync pour iOS, nous pouvons recueillir, avec votre autorisation explicite, des données de santé et de condition physique provenant d'Apple Santé, notamment :
<ul>
    <li><strong>Glycémie :</strong> mesures de la glycémie provenant de capteurs de glucose en continu et saisies manuelles.</li>
    <li><strong>Signes vitaux :</strong> fréquence cardiaque, variabilité de la fréquence cardiaque, tension artérielle, saturation en oxygène du sang, fréquence respiratoire.</li>
    <li><strong>Mensurations :</strong> poids, IMC, pourcentage de graisse corporelle, taille.</li>
    <li><strong>Activité :</strong> pas, énergie active dépensée, entraînements, vélo, natation.</li>
    <li><strong>Sommeil :</strong> phases de sommeil (paradoxal, essentiel, profond), temps passé au lit.</li>
    <li><strong>Nutrition :</strong> apport calorique, macronutriments, vitamines, minéraux, consommation d'eau.</li>
    <li><strong>Autres :</strong> données sur la mobilité, la santé reproductive, l'audition, la pleine conscience et les médicaments.</li>
</ul>
Ces données sont recueillies en lecture seule. Acara Health Sync n'écrit aucune donnée dans Apple Santé. Toutes les données d'Apple Santé sont chiffrées sur votre appareil avant leur transmission et envoyées directement à votre instance d'Acara Plate. Les données d'Apple Santé servent uniquement à vous offrir des conseils nutritionnels personnalisés et des aperçus sur votre santé par l'intermédiaire d'Altani, votre coach santé IA. Nous n'utilisons pas les données d'Apple Santé à des fins de publicité, de marketing ou d'exploration de données.
</p>
<p>
    <strong>c. Renseignements non personnels :</strong>
    Nous pouvons recueillir des données anonymisées ou agrégées, comme des statistiques d'utilisation (p. ex., pages
    consultées, temps passé dans les Services), afin d'améliorer la plateforme.
</p>
<p>
    <strong>d. Témoins et suivi :</strong>
    Nous utilisons des témoins (cookies) et des technologies semblables pour améliorer votre expérience, analyser
    l'utilisation et améliorer nos Services. Vous pouvez gérer vos préférences en matière de témoins dans les paramètres
    de votre navigateur.
</p>
<p>
    <strong>e. Estimations de repas par l'IA et vos modifications :</strong>
    Lorsque vous enregistrez un repas à partir d'une photo, nous conservons l'estimation initiale de l'IA avec ce repas :
    les aliments reconnus, leurs portions, les calories et les macronutriments, le niveau de confiance de l'IA et la
    version de notre analyse qui l'a produite. Si vous modifiez ensuite les aliments ou les quantités du repas, nous
    notons aussi ce que vous avez changé. Cet enregistrement ne comprend jamais votre photo, vos notes ni le nom de votre
    repas.
</p>

<h2>2. Utilisation de vos renseignements</h2>
<p>Nous utilisons vos données pour fournir et améliorer les Services, notamment pour :</p>
<ul>
    <li>Générer des plans de repas et des recommandations alimentaires personnalisés en fonction de vos réponses au
        questionnaire.</li>
    <li>Filtrer les plans de repas selon vos restrictions alimentaires (p. ex., allergies, alimentation végétalienne).</li>
    <li>Gérer votre compte et communiquer avec vous (p. ex., mises à jour du service).</li>
    <li>Analyser des données anonymisées afin d'améliorer les Services et de développer de nouvelles fonctionnalités.</li>
    <li>Mesurer et améliorer la précision de nos estimations de repas. Pour cela, nous examinons uniquement des
        statistiques agrégées, comme la fréquence à laquelle les estimations d'un aliment sont corrigées, et seulement
        pour des groupes d'au moins 10 repas. Personne n'examine vos repas individuels à cette fin.</li>
    <li>Si vous activez <strong>Aider à améliorer la reconnaissance des aliments</strong> (cette option reste désactivée
        tant que vous ne la choisissez pas), notre équipe peut consulter vos repas individuels, vos modifications et vos
        photos de repas pour tester et améliorer la façon dont notre IA reconnaît les aliments. Ces données restent chez
        Acara et ne sont jamais communiquées à d'autres organisations pour leur propre usage. Avant que nous utilisions
        une photo, un fournisseur de services d'IA (voir la section 5) vérifie si elle montre des visages ou d'autres
        renseignements personnels. Vous pouvez désactiver cette option à tout moment dans Paramètres → Confidentialité;
        nous cessons alors de les utiliser à cette fin et supprimons les résultats de ces vérifications.</li>
</ul>
<p>Vos données ne seront pas utilisées à d'autres fins que celles décrites dans la présente politique sans votre
    consentement. Consultez la section 5 pour connaître les flux de données propres aux fonctionnalités assistées par
    l'IA.</p>

<h2>3. Fondements juridiques du traitement (RGPD)</h2>
<p>Pour les utilisateurs de l'Union européenne, nous traitons les données personnelles sur les fondements juridiques suivants :</p>
<ul>
    <li><strong>Consentement :</strong> Vous donnez votre consentement en remplissant le questionnaire ou en créant un
        compte.</li>
    <li><strong>Consentement explicite (article 9) :</strong> Pour les catégories particulières de données (problèmes de santé, médicaments, données biométriques, repas, mesures de la glycémie et autres renseignements liés à la santé), nous nous fondons sur votre consentement explicite, que vous donnez au moyen d'une case à cocher distincte lors de votre inscription. Nous conservons une trace du moment où vous l'avez donné. Vous pouvez retirer ce consentement à tout moment (voir la section 8); comme les Services reposent sur ces renseignements, le retirer signifie fermer votre compte.</li>
    <li><strong>Contrat :</strong> Le traitement est nécessaire pour fournir les Services (p. ex., générer des plans de
        repas).</li>
    <li><strong>Intérêts légitimes :</strong> Nous utilisons des données anonymisées, ainsi que des statistiques de
        précision agrégées tirées des estimations de repas enregistrées par l'IA (voir la section 2), pour améliorer les
        Services, en limitant au minimum l'incidence sur votre vie privée.</li>
</ul>

<h2>4. Communication des données</h2>
<p>Nous ne vendons pas vos renseignements personnels. Nous les communiquons uniquement :</p>
<ul>
    <li>Aux <strong>fournisseurs de services</strong> auxquels nous faisons appel pour exploiter les Services, notamment des fournisseurs d'hébergement et de livraison de courriels, ainsi que des <strong>fournisseurs de services d'IA</strong> qui traitent vos données pour générer des réponses, des résumés, des plongements (embeddings) et des transcriptions (voir la section 5 pour la liste actuelle et les catégories de données transmises). Tous les fournisseurs de services sont liés par des ententes de traitement des données et des obligations de confidentialité.</li>
    <li>Lorsque la loi l'exige (p. ex., pour respecter des obligations légales ou protéger la sécurité des utilisateurs).</li>
    <li>Sous forme anonymisée ou agrégée, à des fins d'analyse ou de recherche visant à améliorer les Services.</li>
</ul>

<h2>5. Traitement par l'IA et fournisseurs tiers de grands modèles de langage</h2>
<p>
    Acara Plate fait appel à des fournisseurs tiers de services d'intelligence artificielle (IA) pour faire fonctionner des fonctionnalités comme Altani (votre coach santé IA), la génération de plans de repas, les aperçus sur la glycémie, les résumés de conversation et d'autres conseils assistés par l'IA. Lorsque vous utilisez ces fonctionnalités, un sous-ensemble limité de vos renseignements personnels, propre à cette fin, est transmis à ces fournisseurs pour l'inférence.
</p>
<p>
    <strong>a. Fournisseurs que nous utilisons actuellement :</strong>
<ul>
    <li><strong>OpenAI</strong> — clavardage (l'agent conversationnel Altani), génération de plans de repas et suggestions de repas au jour le jour, aperçus sur la glycémie, résumés de conversation, transcription audio, plongements de texte et vérification des photos de repas que vous nous permettez d'utiliser pour améliorer la reconnaissance des aliments, afin d'y repérer les visages et autres renseignements personnels (voir la section 2).</li>
    <li><strong>Google</strong> — analyse des photos de repas et fonctionnalités de mémoire à long terme d'Acara Cloud, au moyen de Gemini et de tout modèle successeur ou spécialisé hébergé par Google et offert par la même interface de programmation (API) de Google.</li>
</ul>
Nous indiquons les <strong>sous-traitants</strong>, et non les modèles individuels. Passer à un autre modèle offert par le même sous-traitant (p. ex., une version plus récente de Gemini ou un modèle médical spécialisé hébergé par Google) ne change pas l'entreprise qui reçoit vos données et ne nécessite pas d'avis distinct. Nous mettrons cette liste à jour uniquement lorsqu'un nouveau <strong>sous-traitant</strong> (une autre entreprise ou un déploiement autohébergé) sera ajouté pour vos données.
</p>
<p>
    <strong>b. Données transmises aux fournisseurs d'IA :</strong>
    Lorsque vous utilisez une fonctionnalité assistée par l'IA, nous transmettons :
<ul>
    <li>Le texte de votre message.</li>
    <li>Les messages précédents de la conversation en cours (pour le contexte et les résumés).</li>
    <li>Un « résumé de profil » réduit qui contient votre âge, votre taille, votre poids, votre sexe, votre IMC, vos besoins caloriques quotidiens estimés, vos préférences alimentaires, vos objectifs structurés et votre type d'alimentation. <strong>Nous n'incluons pas dans ce résumé votre date de naissance, votre groupe sanguin, vos médicaments, vos problèmes de santé précis ni le champ « Contexte du ménage ».</strong></li>
    <li>Votre champ en texte libre « Objectifs supplémentaires », <strong>uniquement lorsque l'IA demande expressément vos objectifs</strong> au moyen d'un appel d'outil dédié (par exemple, pour répondre à une question sur l'entraînement ou le bien-être).</li>
    <li>Vos problèmes de santé précis, vos médicaments ou vos mesures détaillées d'Apple Santé, <strong>uniquement lorsque l'IA les demande expressément</strong> au moyen d'un appel d'outil dédié pour répondre à une question liée à la santé.</li>
    <li>Les images que vous choisissez de transmettre à l'IA pour l'analyse d'aliments ou d'étiquettes.</li>
    <li>Les photos de repas que vous numérisez avec Snap to Track lorsque vous avez ouvert une session. Ces photos sont aussi conservées de façon privée avec votre journal alimentaire, comme le décrit la section 7.</li>
</ul>
</p>
<p>
    <strong>Remarque sur la conservation des conversations :</strong>
    Une fois que l'IA a reçu l'une ou l'autre des données ci-dessus au moyen d'un appel d'outil, ces données sont conservées avec le message de la conversation en tant que « résultat d'outil » et peuvent être transmises de nouveau au fournisseur d'IA lors des échanges suivants de la même conversation afin de préserver le contexte. Supprimer la conversation les retire du contexte futur. Nous n'effaçons pas actuellement les résultats d'outils de l'historique des conversations conservé.
</p>
<p>
    <strong>c. Ce que nous ne faisons pas :</strong>
<ul>
    <li>Nous ne soumettons vos données à aucune interface de produit sous notre contrôle qui pourrait servir à l'entraînement. Nous accédons aux fournisseurs au moyen de leurs points de terminaison d'API standard, et non de leurs applications grand public ou de leurs interfaces d'annotation de rétroaction.</li>
    <li>Au-delà de ce que nous transmettons, la façon dont un fournisseur conserve, traite ou utilise vos données est régie par sa propre politique d'utilisation des données de l'API, et non par des contrôles supplémentaires exploités par Acara Plate. Nous n'exploitons pas actuellement de routage sans conservation, de points de terminaison admissibles à un BAA ni de traitement limité à une région, et nous ne vérifions pas de façon indépendante les paramètres de conservation des fournisseurs. Si vous avez besoin de ces garanties, veuillez consulter directement les conditions de chaque fournisseur avant d'utiliser les fonctionnalités assistées par l'IA.</li>
    <li>Nous ne communiquons pas vos données aux fournisseurs d'IA à des fins de publicité, de profilage entre services ni à toute autre fin que la génération de la réponse que vous avez demandée et la vérification des photos décrite à la section 2.</li>
    <li>Nous n'utilisons pas vos photos de repas, vos repas ni vos modifications pour entraîner des modèles d'IA, et nous ne les communiquons pas à d'autres organisations à des fins de recherche ou d'évaluation, sauf si vous nous en donnez l'autorisation distincte.</li>
    <li>Nous n'insérons pas par défaut vos notes personnelles en texte libre (comme « Objectifs supplémentaires » ou « Contexte du ménage ») dans les requêtes envoyées à l'IA.</li>
    <li>Nous ne permettons pas à l'IA d'effectuer des recherches sur le Web lorsque votre demande en cours porte sur vos renseignements personnels ou médicaux; dans ce mode, l'IA ne peut pas lancer de recherches sur le Web en votre nom.</li>
</ul>
</p>
<p>
    <strong>d. Transferts internationaux :</strong>
    Les fournisseurs d'IA traitent les données sur des serveurs situés à l'extérieur du Canada (principalement aux États-Unis et dans l'Union européenne). Lorsque ces fournisseurs relèvent de territoires qui imposent des restrictions au transfert de données, nous nous appuyons sur des clauses contractuelles types ou sur des garanties équivalentes (voir la section 9).
</p>
<p>
    <strong>e. Vos choix :</strong>
<ul>
    <li>Vous pouvez éviter de transmettre les champs en texte libre (comme « Objectifs supplémentaires » ou « Contexte du ménage ») aux fournisseurs d'IA en les laissant simplement vides.</li>
    <li>Vous pouvez demander la suppression de vos données à tout moment (voir la section 8).</li>
    <li>Si vous préférez ne pas utiliser du tout les fonctionnalités assistées par l'IA, ne lancez pas de conversation avec Altani et n'utilisez pas les plans de repas générés par l'IA; les fonctionnalités de l'application qui n'utilisent pas l'IA restent accessibles.</li>
</ul>
</p>
<p>
    <strong>f. Service non visé par la HIPAA :</strong>
    Acara Plate est une application grand public de santé et de nutrition. Elle n'est pas une entité visée par la HIPAA et ne prétend pas offrir un traitement des renseignements médicaux protégés (PHI) conforme à la HIPAA. N'utilisez pas les Services pour transmettre des PHI d'une manière qui exigerait les protections de la HIPAA.
</p>

